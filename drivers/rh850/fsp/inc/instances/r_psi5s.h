/** Default reset value for most PSI5S registers */
#define PSI5S_REG_RESET_VALUE           (0x00000000U) ///< Exceptions: PSI5SjPUBPR, PSI5SjPTFIS, PSI5SjPDDDn

/** Number of PSI5S channels */
#define PSI5S_NUM_CHANNELS              (8U)          ///< CH0 to CH7

/** Number of PSI5S packet frames supported by each channel */
#define PSI5S_CH0_NUM_PACKET_FRAMES     (2U)          ///< CH0 only supports FID = 0b000 and 0b001
#define PSI5S_NUM_PACKET_FRAMES         (6U)          ///< CH1 to CH7 support FID = 0b000 to 101

/** Number packet (UART frame) */
#define PSI5S_CMD_NUM_PACKET            (6U)

/** PSI5S Channel Control */
#define PSI5S_CHANNEL_ENABLE            (1U) /* PRQA S 1534 # Advisory R-2.5 */
#define PSI5S_CHANNEL_DISABLE           (0U) /* PRQA S 1534 # Advisory R-2.5 */

/** PSI5S Watchdog Timer Control */
#define PSI5S_WATCHDOG_TIMER_ENABLE     (1U) /* PRQA S 1534 # Advisory R-2.5 */
#define PSI5S_WATCHDOG_TIMER_DISABLE    (0U) /* PRQA S 1534 # Advisory R-2.5 */

/***********************************************************************************************************************
 * Typedef definitions
 **********************************************************************************************************************/

/** PSI5S setting channel timestamp counter Enable */
typedef enum e_psi5s_timestamp_counter                      /* PRQA S 1536 # Advisory R-2.4 */
{
    PSI5S_TIMESTAMP_COUNTER_DISABLE = 0U,                   ///< Timestamp counter A/B disable
    PSI5S_TIMESTAMP_COUNTER_ENABLE                          ///< Timestamp counter A/B enable
} psi5s_timestamp_counter_t;

/** PSI5S setting channel source signal selection */
typedef enum e_psi5s_signal_src_select                      /* PRQA S 1536 # Advisory R-2.4 */
{
    PSI5S_SIGNAL_SRC_SELECT_PSI5S_SIGNAL = 0U,              ///< Signal generated by PSI5S is selected
    PSI5S_SIGNAL_SRC_SELECT_GTM_ATU_SIGNAL                  ///< Signal GTM/ATU output is selected
} psi5s_signal_src_select_t;

/** PSI5S UART-community RX/TX Parity Set */
typedef enum e_psi5s_parity_setting                         /* PRQA S 1536 # Advisory R-2.4 */
{
    PSI5S_PARITY_SETTING_DISABLE = 0U,                      ///< UART parity disable
    PSI5S_PARITY_SETTING_EVEN,                              ///< UART even parity
    PSI5S_PARITY_SETTING_ZERO_OR_IGNORE,                    ///< UART TX zero parity, RX parity do not care
    PSI5S_PARITY_SETTING_ODD                                ///< UART odd parity
} psi5s_parity_setting_t;

/** PSI5S operation status */
typedef enum e_psi5s_operation_status                       /* PRQA S 1536 # Advisory R-2.4 */
{
    PSI5S_OPERATION_STATUS_IDLE = 0U,                       ///< PSI5S operation idle
    PSI5S_OPERATION_STATUS_BUSY                             ///< PSI5S operation writing/shifting
} psi5s_operation_status_t;

/** PSI5S start status */
typedef enum e_psi5s_start_status                           /* PRQA S 1536 # Advisory R-2.4 */
{
    PSI5S_START_STATUS_DISABLE = 0U,                        ///< PSI5S module is not opened yet
    PSI5S_START_STATUS_ENABLE                               ///< PSI5S module opened
} psi5s_start_status_t;

/** PSI5S frame packet number */
typedef enum e_psi5s_frame_packet_number                    /* PRQA S 1536 # Advisory R-2.4 */
{
    PSI5S_FRAME_PACKET_NUMBER_IGNORE = 0U,                  ///< Frame data is ignored
    PSI5S_FRAME_PACKET_NUMBER_3      = 3U,                  ///< Packet number is set to 3
    PSI5S_FRAME_PACKET_NUMBER_4      = 4U,                  ///< Packet number is set to 4
    PSI5S_FRAME_PACKET_NUMBER_5      = 5U,                  ///< Packet number is set to 5
    PSI5S_FRAME_PACKET_NUMBER_6      = 6U                   ///< Packet number is set to 6
} psi5s_frame_packet_number_t;

/** PSI5S RX timestamp capture trigger selection */
typedef enum e_psi5s_ts_capture_trigger                     /* PRQA S 1536 # Advisory R-2.4 */
{
    PSI5S_TS_CAPTURE_TRIGGER_TRANS_SYNC_PULSE = 0U,         ///< Transmission synchronous pulse timing selected
    PSI5S_TS_CAPTURE_TRIGGER_HEADER_RECEIVE                 ///< Header receive timing selected
} psi5s_ts_capture_trigger_t;

/** PSI5S RX timestamp counter selection */
typedef enum e_psi5s_ts_counter_select                      /* PRQA S 1536 # Advisory R-2.4 */
{
    PSI5S_TS_COUNTER_SELECT_B = 0U,                         ///< Timestamp counter B selected
    PSI5S_TS_COUNTER_SELECT_A                               ///< Timestamp counter A selected
} psi5s_ts_counter_select_t;

/** PSI5S RX timestamp capture enable */
typedef enum e_psi5s_ts_capture                             /* PRQA S 1536 # Advisory R-2.4 */
{
    PSI5S_TS_CAPTURE_DISABLE = 0U,                          ///< Timestamp capture disable
    PSI5S_TS_CAPTURE_ENABLE                                 ///< Timestamp capture enable
} psi5s_ts_capture_t;

/** PSI5S RX frame checksum CRC/parity selection */
typedef enum e_psi5s_checksum                               /* PRQA S 1536 # Advisory R-2.4 */
{
    PSI5S_CHECKSUM_PARITY = 0U,                             ///< Parity selected
    PSI5S_CHECKSUM_CRC                                      ///< CRC selected
} psi5s_checksum_t;

/** PSI5S timestamp counter setting */
typedef struct st_psi5s_ts_counter_setting                  /* PRQA S 1536 # Advisory R-2.4 */
{
    psi5s_timestamp_counter_t timestamp_counter_enable;     ///< Setting timestamp counter enable
    psi5s_signal_src_select_t counter_clear_select;         ///< Clear source signal selection
    psi5s_signal_src_select_t counter_enable_select;        ///< Enable source signal selection
    psi5s_signal_src_select_t counter_clock_select;         ///< Clock source signal selection
} psi5s_ts_counter_setting_t;

/** PSI5S timestamp setting */
typedef struct st_psi5s_timestamp_setting                   /* PRQA S 1536 # Advisory R-2.4 */
{
    uint32_t timestamp_prescaler;                           ///< Setting timestamp pre-scaler value

    psi5s_ts_counter_setting_t const * timestamp_counter_a; ///< Timestamp counter A setting
    psi5s_ts_counter_setting_t const * timestamp_counter_b; ///< Timestamp counter B setting
} psi5s_timestamp_setting_t;

/** PSI5S register settings to achieve a desired baud rate */
typedef struct st_psi5s_baud_setting                        /* PRQA S 1536 # Advisory R-2.4 */
{
    uint8_t bit_sampling;                                   ///< RX over sample number (default 4: 5 samples)
    uint8_t prescaler;                                      ///< Pre-scaler of UART SCLK (psis_tx_sclk)
    uint8_t divider;                                        ///< Clock divide value of UART SCLK (psis_tx_sclk)
} psi5s_baud_setting_t;

/** PSI5S watchdog timer setting */
typedef struct st_psi5s_wdt_setting                         /* PRQA S 1536 # Advisory R-2.4 */
{
    uint8_t  wdt_enable;                                    ///< Watchdog timer of RX frame enable
    uint16_t wdt_prescaler;                                 ///< Watchdog timer pre-scaler
    uint32_t wdt_expire_value;                              ///< Watchdog timer expiration value
} psi5s_wdt_setting_t;

/** PSI5S sync pulse trigger setting */
typedef struct st_psi5s_sync_pulse_setting                  /* PRQA S 1536 # Advisory R-2.4 */
{
    psi5s_signal_src_select_t sync_pulse_src_select;        ///< Sync trigger source select
    uint16_t sync_pulse_prescaler;                          ///< Synchronous trigger generation counter pre-scaler
    uint32_t sync_pulse_expire_value;                       ///< Synchronous trigger generation counter expiration value
} psi5s_sync_pulse_setting_t;

/** PSI5S frame packet setting */
typedef struct st_psi5s_frame_packet_cfg                    /* PRQA S 1536 # Advisory R-2.4 */
{
    psi5s_frame_packet_number_t packet_number;              ///< Frame packet number
    uint8_t payload_bit_length;                             ///< The pay load bit length of packet frame
} psi5s_frame_packet_cfg_t;

/** PSI5S frame receive setting */
typedef struct st_psi5s_frame_rx_setting                    /* PRQA S 1536 # Advisory R-2.4 */
{
    psi5s_frame_packet_cfg_t const * frame_packet;          ///< Channel frame (1->6) packet number
    psi5s_sync_mode_select_t         sync_mode;             ///< Channel synchronization mode select
    psi5s_ts_capture_trigger_t       ts_cap_trigger;        ///< Channel timestamp capture trigger select
    psi5s_ts_counter_select_t        ts_count_sel;          ///< Channel timestamp counter select
    psi5s_ts_capture_t               ts_capture_en;         ///< Channel timestamp capture enable
    psi5s_checksum_t                 checksum;              ///< Channel RX frame checksum select
    uint8_t channel_en;                                     ///< Channel enable
} psi5s_frame_rx_setting_t;

/** PSI5S error and event context records */
typedef struct st_psi5s_event_context                       /* PRQA S 1536 # Advisory R-2.4 */
{
    psi5s_packet_frame_t event_packet_frame;                ///< PSI5S event/error packet frame
    psi5s_channel_t      channel;                           ///< PSI5S channel
} psi5s_event_context_t;

/** Control block used by driver. DO NOT INITIALIZE - this structure will be initialized in @ref psi5s_api_t::open. */
typedef struct st_psi5s_instance_ctrl                       /* PRQA S 1536 # Advisory R-2.4 */
{
    R_PSI5S0_Type * p_reg;                                  ///< Pointer to PSI5S unit register base address

    /** Generic status */
    uint32_t                 open;                          ///< Driver ID
    psi5s_operation_status_t cur_status;                    ///< PSI5S operation status
    psi5s_start_status_t     cur_start_status;              ///< PSI5S start status

    /** Generic configuration */
    psi5s_loopback_mode_t cur_loopback_mode;                ///< PSI5S loopback mode

    /** TX CMD */
    uint8_t cur_tdt[8];
    uint8_t cur_txnum;

    /** RX mailbox */
    psi5s_mailbox_t psi5s_mailbox[PSI5S_NUM_CHANNELS][PSI5S_NUM_PACKET_FRAMES]; ///< Software buffer stores received data

    /** Parameters to control software behavior */
    void (* p_callback)(psi5s_callback_args_t * p_args);                        ///< Pointer to callback
    psi5s_callback_args_t * p_callback_memory;                                  ///< Pointer to optional callback argument memory
    void const            * p_context;                                          ///< Pointer to context to be passed into callback function
    psi5s_cfg_t const     * p_cfg;                                              ///< Pointer to configuration block
} psi5s_instance_ctrl_t;

/** PSI5S extended configuration */
typedef struct st_psi5s_extended_cfg                                            /* PRQA S 1536 # Advisory R-2.4 */
{
    psi5s_baud_setting_t const * uart_baud_setting;                             ///< Baud rate setting

    psi5s_parity_setting_t tx_parity_setting;                                   ///< TX UART parity setting
    psi5s_parity_setting_t rx_parity_setting;                                   ///< RX UART parity setting

    psi5s_timestamp_setting_t const * timestamp_setting;                        ///< PSI5S timestamp setting

    psi5s_wdt_setting_t const * psi5s_wdt_setting;                              ///< PSI5S WDT config for CH n

    psi5s_sync_pulse_setting_t const * psi5s_sync_pulse_setting;                ///< PSI5S sync pulse config for CH n

    psi5s_frame_rx_setting_t const * psi5s_frame_rx_setting;                    ///< PSI5S frame reception config for CH sn
} psi5s_extended_cfg_t;

